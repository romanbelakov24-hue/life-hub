/**
 * Сравнение токенов за постоянное время.
 *
 * Обычное `===` возвращает результат, как только находит первое несовпадение,
 * поэтому время сравнения слегка зависит от того, сколько начальных символов
 * угадано верно. На случайных 128-битных токенах эта разница ничтожна, но
 * убрать её отсюда дешевле, чем объяснять, почему полагались на «ничтожна».
 *
 * Используется везде, где токен в URL или заголовке — единственная защита
 * маршрута без авторизации: календарная лента, страница-сводка, приём данных
 * здоровья.
 */
export function safeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;

  let diff = 0;
  for (let index = 0; index < a.length; index += 1) {
    diff |= a.charCodeAt(index) ^ b.charCodeAt(index);
  }
  return diff === 0;
}
