import type { CapacitorConfig } from "@capacitor/cli";

/**
 * Конфигурация мобильной обёртки.
 *
 * Приложение загружает живой сайт, а не собранные внутрь файлы. Это не
 * упрощение, а следствие архитектуры: страницы отрисовываются на сервере
 * (`force-dynamic`), запись идёт через серверные действия, и статически
 * выгрузить такой проект нельзя — `output: "export"` сломает и то, и другое.
 *
 * Что это значит на практике:
 *   • приложение бесполезно, пока сайт недоступен с устройства. Задача с
 *     хостингом идёт строго раньше сборки APK;
 *   • нативные возможности (календарь, здоровье, чтение уведомлений) всё равно
 *     доступны: Capacitor пробрасывает мост в WebView и для удалённого адреса;
 *   • App Store к «обёрткам вокруг сайта» относится строго — см. правило 4.2
 *     про минимальную функциональность. Для RuStore и Google Play это норма.
 *
 * Адрес берётся из переменной окружения: при переезде на другой хостинг
 * пересобирать конфиг руками не придётся.
 */

const SITE_URL = process.env.CAPACITOR_SERVER_URL ?? "https://life-hub8.netlify.app";

const config: CapacitorConfig = {
  // Идентификатор фиксируется при первой публикации и потом не меняется —
  // в сторах это первичный ключ приложения.
  appId: "ru.lifehub.client",
  appName: "life hub",

  // Локальные файлы-заглушки. Показываются, только если сайт не открылся:
  // без них WebView отдал бы системную страницу ошибки.
  webDir: "capacitor-shell",

  server: {
    url: SITE_URL,
    // Разрешаем WebView переходить по ссылкам внутри нашего домена,
    // всё остальное уйдёт во внешний браузер.
    allowNavigation: [new URL(SITE_URL).host],
  },

  android: {
    // Только https: открытым http в мобильном приложении делать нечего.
    allowMixedContent: false,
  },
};

export default config;
